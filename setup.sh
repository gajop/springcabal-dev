#!/usr/bin/env bash
# Set up a SpringCabal development checkout.
#
#   ./setup.sh                      clone the game/map repos listed in content.tsv
#                                   and the private springcabal-rs crate, and write
#                                   .cargo/config.toml if there is none yet
#   ./setup.sh --engine-tag TAG     also download that Linux engine release into
#                                   engine/TAG and point engine/current at it
#   ./setup.sh --dev-engine [PATH]  (re)write .cargo/config.toml to build against
#                                   the engine checkout's crates (default ../spring-bar)
#   ./setup.sh --no-dev-engine      (re)write it without the engine crates
#
# Existing checkouts are never touched.  See README.md for the full workflow.
set -euo pipefail

project_root="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
content_root="$project_root/spring-linux"
engine_repo="gajop/spring-rust"
springcabal_url="ssh://git@github.com/gajop/springcabal-rs.git"
springcabal_dir="$project_root/springcabal-rs"
engine_tag=""
cargo_config=""      # "", engine or no-engine
dev_engine_dir=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --engine-tag) engine_tag="${2:?}"; shift 2 ;;
        --dev-engine)
            cargo_config=engine
            if [[ -n ${2:-} && $2 != -* ]]; then dev_engine_dir=$2; shift; fi
            shift
            ;;
        --no-dev-engine) cargo_config=no-engine; shift ;;
        -h|--help) sed -n 2,13p "$0"; exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 1 ;;
    esac
done

# Prints the package names of the Cargo manifests under a directory.
cargo_packages() {
    local manifest
    while IFS= read -r manifest; do
        awk '/^\[/ { section = $0 }
             section == "[package]" && /^name[[:space:]]*=/ {
                 gsub(/^name[[:space:]]*=[[:space:]]*"|".*$/, ""); print FILENAME "\t" $0; exit
             }' "$manifest"
    done < <(find "$1/" -maxdepth 3 -name Cargo.toml -not -path '*/target/*' | sort)
}

# write_cargo_config [ENGINE_DIR]: the one generator of .cargo/config.toml.
# - With ENGINE_DIR, the spring and spring-addons crates come from its
#   rust/crates/ (engine co-development).
# - The springcabal crates come from springcabal-rs/ when it is checked out.
# - Cargo fetches git dependencies with the git CLI, so the private
#   springcabal-rs repository is fetched with your SSH setup.
# Paths are relative to this directory (the parent of .cargo/), as Cargo
# resolves them.  An existing file that differs is shown as a diff and kept
# as config.toml.bak.
write_cargo_config() {
    local engine_dir=${1:-} crates file="$project_root/.cargo/config.toml" tmp manifest name rel
    tmp=$(mktemp)
    {
        echo "# Generated by ./setup.sh (just setup-dev-engine / remove-dev-engine)."
        echo "# Regenerate it rather than editing it."
        if [[ -n $engine_dir ]]; then
            crates=$(realpath -m -s "$engine_dir/rust/crates")
            if [[ ! -d $crates/spring || ! -d $crates/spring-addons ]]; then
                rm -f -- "$tmp"
                echo "Error: no 'spring' and 'spring-addons' crates in $crates" >&2
                exit 1
            fi
            rel=$(realpath -m -s --relative-to="$project_root" "$crates")
            echo
            echo "# The engine's crates from a local checkout, for engine co-development."
            echo '[patch."https://github.com/gajop/spring-rust"]'
            echo "spring = { path = \"$rel/spring\" }"
            echo "spring-addons = { path = \"$rel/spring-addons\" }"
        fi
        if [[ -d $springcabal_dir ]]; then
            echo
            echo "# The shared SpringCabal crates from the local springcabal-rs checkout."
            echo "[patch.\"$springcabal_url\"]"
            while IFS=$'\t' read -r manifest name; do
                rel=$(realpath -m -s --relative-to="$project_root" "$(dirname "$manifest")")
                echo "$name = { path = \"$rel\" }"
            done < <(cargo_packages "$springcabal_dir")
        fi
        echo
        echo "# springcabal-rs is a private repository: fetch git dependencies with the"
        echo "# git CLI, which uses your SSH key and ~/.ssh/config."
        echo "[net]"
        echo "git-fetch-with-cli = true"
    } >"$tmp"

    mkdir -p "$(dirname "$file")"
    if [[ -f $file ]] && cmp -s "$tmp" "$file"; then
        rm -f -- "$tmp"
        echo "==> .cargo/config.toml is up to date"
        return
    fi
    if [[ -f $file ]]; then
        echo "==> Replacing .cargo/config.toml (previous copy: .cargo/config.toml.bak):"
        diff -u "$file" "$tmp" || true
        cp -- "$file" "$file.bak"
    else
        echo "==> Writing .cargo/config.toml"
    fi
    mv -- "$tmp" "$file"
}

if [[ -n "$engine_tag" ]]; then
    engine_dir="$project_root/engine/$engine_tag"
    if [[ ! -x "$engine_dir/spring" ]]; then
        asset="recoil_${engine_tag}_amd64-linux.7z"
        echo "==> Downloading $asset from $engine_repo"
        tmp="$(mktemp -d)"
        gh release download "$engine_tag" -R "$engine_repo" -p "$asset" -D "$tmp"
        mkdir -p "$engine_dir"
        7z x -bso0 -bsp0 -o"$engine_dir" "$tmp/$asset"
        rm -rf -- "$tmp"
    fi
    ln -sfn "$engine_tag" "$project_root/engine/current"
    echo "==> engine/current -> $engine_tag"
fi

case "$cargo_config" in
    engine)
        if [[ -z $dev_engine_dir ]]; then
            dev_engine_dir="$(dirname "$project_root")/spring-bar"
        fi
        write_cargo_config "$dev_engine_dir"
        echo "    Local engine crates from $dev_engine_dir are used when compiling games."
        exit 0
        ;;
    no-engine)
        write_cargo_config
        echo "    Games compile against the engine crates from $engine_repo (git)."
        exit 0
        ;;
esac

mkdir -p "$content_root/games" "$content_root/maps" "$content_root/projects"

missing=()
while IFS=$'\t' read -r kind path source branch ship; do
    dst="$content_root/${kind}s/$path"
    [[ -e "$dst" ]] && continue
    case "$source" in
        local|download)
            missing+=("$kind/$path ($source)")
            ;;
        *)
            echo "==> Cloning $kind/$path ($branch)"
            if ! git clone --recursive --branch "$branch" "$source" "$dst"; then
                missing+=("$kind/$path (branch $branch not available from $source)")
            fi
            ;;
    esac
done < <(grep -v -E '^\s*(#|$)' "$project_root/content.tsv")

# The shared crate every WASM game depends on.  It is private: cloning needs
# SSH access to github.com/gajop/springcabal-rs.
if [[ ! -e $springcabal_dir ]]; then
    echo "==> Cloning springcabal-rs"
    if ! git clone "$springcabal_url" "$springcabal_dir"; then
        missing+=("springcabal-rs (needs SSH access to $springcabal_url)")
    fi
fi

# A fresh checkout gets a config; an existing one is yours (--dev-engine or
# --no-dev-engine rewrite it).
if [[ ! -f $project_root/.cargo/config.toml ]]; then
    default_engine="$(dirname "$project_root")/spring-bar"
    if [[ -d $default_engine/rust/crates/spring ]]; then
        write_cargo_config "$default_engine"
    else
        write_cargo_config
    fi
fi

if (( ${#missing[@]} )); then
    echo ""
    echo "Not set up automatically; copy these into place by hand:"
    printf '  %s\n' "${missing[@]}"
fi
